// Expo config plugin: declare the two Health Connect READ permissions, and
// nothing else.
//
// WHY THIS EXISTS: react-native-health-connect ships its own plugin, but that one
// only adds the ACTION_SHOW_PERMISSIONS_RATIONALE intent-filter. The
// `<uses-permission>` entries are ours to declare, and declaring them is the
// whole security posture of this feature:
//
//   READ ONLY, AND ONLY TWO TYPES. There is no WRITE_* permission here, so no
//   write-back path to the health platform EXISTS - not "is not called", does not
//   exist. That is the structural half of the one-way guarantee in
//   proposals/2026-07-30-health-import.md. The other half is the iOS side asking
//   for `toRead` and never `toShare`.
//
// Google's own guidance for the Play Console health declaration is to request the
// minimum data types with a specific user-facing justification, so keeping this
// list to exactly what the import writes is also what gets the declaration
// approved. Anything added here needs a matching justification on the form.
//
// Health Connect is part of the platform from Android 14 (API 34). Below that it
// is a separate app the user may not have, which the shell handles at runtime by
// reporting it unavailable rather than failing.

const { withAndroidManifest, withMainActivity } = require('expo/config-plugins')

// Exactly the two the import reads. See src/healthImport.js IMPORTABLE.
const PERMISSIONS = [
  'android.permission.health.READ_MENSTRUATION',
  'android.permission.health.READ_BASAL_BODY_TEMPERATURE',
]

// react-native-health-connect registers its permission-result launcher from the
// host Activity's onCreate, and a launcher must be registered BEFORE the activity
// starts. Without it the first import crashes the app with
// `UninitializedPropertyAccessException: lateinit property requestPermission has
// not been initialized` - found on the API 34 emulator 2026-07-30, not by reading
// the README. The library documents a manual MainActivity edit, but `android/` is
// generated by prebuild, so the edit has to happen here or it is wiped.
const DELEGATE_IMPORT = 'import dev.matinzd.healthconnect.permissions.HealthConnectPermissionDelegate'
const DELEGATE_CALL = '    HealthConnectPermissionDelegate.setPermissionDelegate(this)'

function withHealthConnectActivity (config) {
  return withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== 'kt') {
      throw new Error('with-android-health-connect: expected a Kotlin MainActivity, got ' + cfg.modResults.language)
    }
    let src = cfg.modResults.contents
    if (!src.includes(DELEGATE_IMPORT)) {
      src = src.replace('import com.facebook.react.ReactActivity', DELEGATE_IMPORT + '\nimport com.facebook.react.ReactActivity')
    }
    if (!src.includes('setPermissionDelegate')) {
      // After super.onCreate, so the activity is far enough along to register a
      // result launcher, and still before any JS can ask to import.
      const anchor = 'super.onCreate(null)'
      if (!src.includes(anchor)) throw new Error('with-android-health-connect: could not find super.onCreate in MainActivity')
      src = src.replace(anchor, anchor + '\n' + DELEGATE_CALL)
    }
    cfg.modResults.contents = src
    return cfg
  })
}

module.exports = function withAndroidHealthConnect (config) {
  config = withHealthConnectActivity(config)
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest
    manifest['uses-permission'] = manifest['uses-permission'] || []
    for (const name of PERMISSIONS) {
      if (!manifest['uses-permission'].some((p) => p.$?.['android:name'] === name)) {
        manifest['uses-permission'].push({ $: { 'android:name': name } })
      }
    }
    return cfg
  })
}
