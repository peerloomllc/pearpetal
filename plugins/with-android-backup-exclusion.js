// Expo config plugin: keep the private cycle store out of Google's CLOUD backup,
// while still allowing a direct phone-to-phone transfer.
//
// WHY THIS EXISTS: the Corestore lives under the app's files directory
// (app/index.tsx passes FileSystem.documentDirectory to the worklet's init, and
// @peerloom/core opens `<dataDir>/pearpetal/store`). Android's Auto Backup is ON
// by default (`android:allowBackup="true"` with no extraction rules), so without
// this the whole private cycle log - every logged day, flow, symptom, note and
// BBT - is eligible to be copied to the user's Google Drive, while onboarding
// promises "no accounts, no servers. Your data stays on your device."
//
// THE SPLIT IS DELIBERATE. Android 12+ lets cloud backup and device-to-device
// transfer be configured separately, and they are not the same thing for this app:
//   - CLOUD BACKUP puts the log in a third party's storage. Excluded.
//   - DEVICE TRANSFER moves it straight from the user's old phone to their new
//     one, which is exactly the "your own devices" model PearPetal already has in
//     device linking. Left enabled.
// Everything else (settings, the resolved theme) stays backed up, so a restore is
// not needlessly hostile - it just starts the cycle log empty, which is what the
// recovery phrase and the JSON export are for.
//
// Android 11 and lower has no such split: `fullBackupContent` rules apply to both
// modes, so on those versions the exclusion also costs D2D transfer. That is the
// safe direction to err.
//
// The iOS half of this job is modules/backup-exclusion (NSURLIsExcludedFromBackupKey).
// See proposals/2026-07-30-health-import.md, which is where this gap was found.

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins')
const fs = require('fs')
const path = require('path')

// Must match APP_STORE_DIR in app/index.tsx and appId in src/bare.js. `domain="file"`
// is the app's files directory, which is what expo maps documentDirectory to.
const STORE_DIR = 'pearpetal'

// Android 12+ (API 31+): cloud backup and device transfer configured separately.
const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-exclusion.js - do not edit by hand. -->
<data-extraction-rules>
  <cloud-backup>
    <!-- The private cycle log never goes to Google's cloud. -->
    <exclude domain="file" path="${STORE_DIR}" />
  </cloud-backup>
  <device-transfer>
    <!-- A direct phone-to-phone move stays on the user's own devices, which is
         the same trust boundary as device linking. Everything included. -->
  </device-transfer>
</data-extraction-rules>
`

// Android 11 and lower: one set of rules for every backup mode.
const BACKUP_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-exclusion.js - do not edit by hand. -->
<full-backup-content>
  <exclude domain="file" path="${STORE_DIR}" />
</full-backup-content>
`

module.exports = function withAndroidBackupExclusion (config) {
  // 1. Write both rule files into res/xml.
  config = withDangerousMod(config, ['android', (cfg) => {
    const resXml = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml')
    fs.mkdirSync(resXml, { recursive: true })
    fs.writeFileSync(path.join(resXml, 'data_extraction_rules.xml'), DATA_EXTRACTION_RULES)
    fs.writeFileSync(path.join(resXml, 'backup_rules.xml'), BACKUP_RULES)
    return cfg
  }])

  // 2. Point the manifest at them. allowBackup stays true on purpose: the rules
  //    above already exclude the one thing that must not leave the device, and
  //    keeping backup on means a user's settings still restore.
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0]
    if (!app) throw new Error('with-android-backup-exclusion: no <application> in the manifest')
    app.$['android:dataExtractionRules'] = '@xml/data_extraction_rules'
    app.$['android:fullBackupContent'] = '@xml/backup_rules'
    app.$['android:allowBackup'] = 'true'
    return cfg
  })
}
